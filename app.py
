import streamlit as st
import google.generativeai as genai
from pypdf import PdfReader

st.set_page_config(
    page_title="Document AI Assistant",
    page_icon="📖",
    layout="wide"
)

st.title("📖 Document Q&A Assistant")

# API కీ మరియు ఫైల్ అప్‌లోడ్ సెట్టింగ్స్
with st.sidebar:
    st.header("కాన్ఫిగరేషన్")
    api_key = st.text_input("Gemini API Key నమోదు చేయండి:", type="password")
    uploaded_files = st.file_uploader(
        "PDF ఫైల్స్ అప్‌లోడ్ చేయండి",
        type=["pdf"],
        accept_multiple_files=True
    )
    if st.button("చాట్ క్లియర్ చేయండి"):
        st.session_state.messages = []
        st.rerun()

# PDF నుండి టెక్స్ట్ సేకరించే ఫంక్షన్
@st.cache_data(show_spinner=False)
def extract_text_from_pdfs(files):
    full_text = ""
    for file in files:
        reader = PdfReader(file)
        for page in reader.pages:
            page_text = page.extract_text()
            if page_text:
                full_text += page_text + "\n"
    return full_text

# కఠినమైన సోర్స్ ఆధారిత సూచన
SYSTEM_INSTRUCTION = (
    "You are a strict document analysis assistant. "
    "Answer questions ONLY using the facts directly mentioned in the provided context. "
    "Do NOT assume, extrapolate, or use outside world knowledge. "
    "If the answer cannot be found in the context, respond strictly with: "
    "'క్షమించండి, అందించిన సమాచారంలో దీనికి సంబంధించిన వివరాలు లేవు.'"
)

# ప్రాథమిక తనిఖీలు
if not api_key:
    st.info("👈 దయచేసి ఎడమవైపు సైడ్‌బార్‌లో మీ Gemini API Key ఎంటర్ చేయండి.")
    st.stop()

if not uploaded_files:
    st.info("👈 దయచేసి ఎడమవైపు సైడ్‌బార్‌లో ఒకటి లేదా అంతకంటే ఎక్కువ PDF ఫైల్స్ అప్‌లోడ్ చేయండి.")
    st.stop()

genai.configure(api_key=api_key)

with st.spinner("డాక్యుమెంట్లను సిద్ధం చేస్తోంది..."):
    context_data = extract_text_from_pdfs(uploaded_files)

# చాట్ సెషన్ హిస్టరీ
if "messages" not in st.session_state:
    st.session_state.messages = []

# మునుపటి మెసేజ్‌లను చూపించడం
for message in st.session_state.messages:
    with st.chat_message(message["role"]):
        st.markdown(message["content"])

# ప్రశ్న ఇన్‌పుట్ & సమాధానం
if prompt := st.chat_input("మీ ప్రశ్నను ఇక్కడ టైప్ చేయండి..."):
    st.session_state.messages.append({"role": "user", "content": prompt})
    with st.chat_message("user"):
        st.markdown(prompt)

    model = genai.GenerativeModel(
        model_name="gemini-1.5-flash",
        system_instruction=SYSTEM_INSTRUCTION
    )

    query_payload = f"Context:\n{context_data}\n\nQuestion:\n{prompt}"

    with st.chat_message("assistant"):
        with st.spinner("సమాధానం వెతుకుతోంది..."):
            try:
                response = model.generate_content(query_payload)
                answer_text = response.text
                st.markdown(answer_text)
                st.session_state.messages.append({"role": "assistant", "content": answer_text})
            except Exception as e:
                error_msg = f"లోపం తలెత్తింది: {e}"
                st.error(error_msg)
                st.session_state.messages.append({"role": "assistant", "content": error_msg})
